function setCypferMode(mode) {
  _cypferState.mode = mode;
  rCypfer();
}

function updateCypfer(key, val) {
  _cypferState[key] = val;
  _cypferUpdatePreview();
}

function copyCypferScript() {
  const text = _cypferRender();
  navigator.clipboard.writeText(text).then(
    () => showToast('Collector script copied to clipboard'),
    () => showToast('Clipboard copy failed')
  );
}

function downloadCypferScript() {
  const text = _cypferRender();
  const name = _cypferState.mode === 'live'
    ? 'collect-local.ps1'
    : `collect-image-${_cypferState.caseName || 'case'}-${_cypferState.hostLabel || 'host'}.ps1`;
  const blob = new Blob([text], { type: 'text/plain;charset=utf-8' });
  const url  = URL.createObjectURL(blob);
  const a    = document.createElement('a');
  a.href     = url;
  a.download = name;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
  showToast(`Downloaded ${name}`);
}
